export const SKILLS: Skill[] = SKILL_GROUPS.flatMap((group) => group.skills);

export function skillById(id: string): Skill | null {
  return SKILLS.find((skill) => skill.id === id) ?? null;
}

const SKILL_NAME_RE = /^[\p{L}][\p{L}\s'./-]{1,47}$/u;

/** A listed title, or a skill the person typed. Typed titles can be changed later. */
export function resolveSkill(id: string, typed: string): Skill | null {
  const text = typed.replace(/\s+/g, " ").trim();
  const listed = skillById(id);
  if (listed && (!text || listed.name.toLowerCase() === text.toLowerCase())) return listed;
  const match = SKILLS.find((skill) => skill.name.toLowerCase() === text.toLowerCase());
  if (match) return match;
  if (!SKILL_NAME_RE.test(text)) return null;
  const slug = text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40);
  if (!slug) return null;
  return { id: `x-${slug}`, name: text };
}
