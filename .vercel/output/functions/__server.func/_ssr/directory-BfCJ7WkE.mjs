function normalizePhone(raw, dial) {
	let digits = raw.replace(/\D/g, "");
	const cc = dial.replace(/\D/g, "");
	if (!digits) return null;
	if (digits.startsWith("0")) digits = cc + digits.slice(1);
	if (!digits.startsWith(cc)) digits = cc + digits;
	if (digits.length < cc.length + 8 || digits.length > cc.length + 12) return null;
	return `+${digits}`;
}
function formatPhone(phone) {
	const digits = phone.replace(/\D/g, "");
	if (digits.startsWith("233") && digits.length === 12) return `+233 ${digits.slice(3, 5)} ${digits.slice(5, 8)} ${digits.slice(8)}`;
	if (digits.startsWith("234") && digits.length >= 13) return `+234 ${digits.slice(3, 6)} ${digits.slice(6, 9)} ${digits.slice(9)}`;
	if (digits.startsWith("254") && digits.length >= 12) return `+254 ${digits.slice(3, 6)} ${digits.slice(6, 9)} ${digits.slice(9)}`;
	if (digits.startsWith("27") && digits.length >= 11) return `+27 ${digits.slice(2, 4)} ${digits.slice(4, 7)} ${digits.slice(7)}`;
	if (digits.startsWith("225") && digits.length >= 12) return `+225 ${digits.slice(3, 5)} ${digits.slice(5, 7)} ${digits.slice(7, 9)} ${digits.slice(9)}`;
	return phone.startsWith("+") ? phone : `+${digits}`;
}
